import type { IRolesProvider } from '@equinor/fusion-framework-module-roles';

import type { RolesMiddlewareMetadata } from './middleware-metadata/types.js';

/**
 * Fetcher execution held by a `requireRoles` denial.
 *
 * - `fetcher-load`: a `fetcher.load()` (or `<fetcher.Form method="get">`) execution.
 * - `fetcher-submission`: a `fetcher.submit()` / `<fetcher.Form>` action execution.
 */
export type RequireRolesFetcherRecoveryOperation = 'fetcher-load' | 'fetcher-submission';

/**
 * Progress of a held fetcher execution.
 *
 * - `waiting`: denied and held; waiting for the user to activate access.
 * - `checking`: a fresh `refresh: true` access check is running.
 * - `still-denied`: the latest fresh check still denied access; the execution stays held.
 * - `check-failed`: the latest fresh check failed; access is unknown and the execution stays held.
 */
export type RequireRolesFetcherRecoveryStatus =
  | 'waiting'
  | 'checking'
  | 'still-denied'
  | 'check-failed';

/**
 * Outcome of {@link RequireRolesFetcherRecovery.retry}.
 *
 * - `resumed`: access confirmed; the original execution continued into loaders/actions.
 * - `still-denied` / `check-failed`: nothing ran; the execution stays held.
 * - `stale`: the execution was already resumed, dismissed or cancelled; nothing ran.
 */
export type RequireRolesFetcherRecoveryResult =
  | 'resumed'
  | 'still-denied'
  | 'check-failed'
  | 'stale';

/** Provider methods the recovery relies on. */
type RolesAccessChecker = Pick<IRolesProvider, 'hasAccessRole'>;

/** Inputs captured by `requireRoles` when it holds a denied fetcher execution. */
export interface RequireRolesFetcherRecoveryInit {
  /** Denial error; thrown into the fetcher when the hold is dismissed. */
  readonly error: Error;
  /** Normalized requirement that was denied. */
  readonly requirement: RolesMiddlewareMetadata;
  /** Roles provider that made the decision. */
  readonly provider: RolesAccessChecker;
  /** Kind of fetcher execution held. */
  readonly operation: RequireRolesFetcherRecoveryOperation;
  /** Fetcher key, as passed to `router.fetch` (generated by `useFetcher` when not explicit). */
  readonly key: string;
  /** Route id of the component that owns the fetcher. */
  readonly routeId: string;
  /** Abort signal of the held execution's request. */
  readonly signal: AbortSignal;
}

/** Monotonic id source; ids identify holds in host UI lists. */
let nextId = 0;

/**
 * A `requireRoles` denial of a fetcher execution that is held, not failed, while the user
 * activates access.
 *
 * React Router reports a fetcher error at the owner's route error boundary, which unmounts the
 * fetcher's owner; a remounted `useFetcher()` gets a new key and can never receive a replay's
 * data. Holding keeps the owner mounted, its fetcher key and `state` (`loading`/`submitting`)
 * unchanged. When {@link retry} confirms access with a fresh `refresh: true` check, the original
 * middleware execution calls `next()`, so the same execution runs the loader or action exactly
 * once and React Router delivers `fetcher.data` and revalidation to every consumer of that key as
 * usual.
 *
 * The hold ends exactly once:
 * - resumed by a successful {@link retry};
 * - dismissed by {@link dismiss}, or when the last recovery host unmounts, which throws the denial
 *   into the fetcher so the owner's error boundary shows it explicitly;
 * - dismissed when a navigation left the owner's route; the owner already unmounted, so React
 *   Router discards the outcome and nothing runs;
 * - cancelled when React Router aborts the execution (resubmitted key, interrupting navigation,
 *   router disposed), which rejects with the abort reason and runs nothing.
 *
 * Render pending holds with {@link useRequireRolesFetcherRecoveries}.
 */
export class RequireRolesFetcherRecovery {
  /** Unique, stable id for UI lists. */
  public readonly id: string;
  /** Denial error, compatible with the existing Roles recovery UI (`RoleErrorView`). */
  public readonly error: Error;
  /** Requirement checked again before resuming. */
  public readonly requirement: RolesMiddlewareMetadata;
  /** Kind of fetcher execution held. */
  public readonly operation: RequireRolesFetcherRecoveryOperation;
  /** Fetcher key of the held execution. */
  public readonly key: string;
  /** Route id of the component that owns the fetcher. */
  public readonly routeId: string;
  /**
   * Settles when the hold ends: resolves when resumed, rejects with the denial when dismissed or
   * with the abort reason when cancelled. The middleware awaits it before calling `next()`.
   */
  public readonly settled: Promise<void>;

  readonly #provider: RolesAccessChecker;
  readonly #listeners = new Set<() => void>();
  #status: RequireRolesFetcherRecoveryStatus = 'waiting';
  #open = true;
  #attempt: Promise<RequireRolesFetcherRecoveryResult> | undefined;
  #resolve!: () => void;
  #reject!: (reason: unknown) => void;

  /**
   * Creates a pending hold for a denied fetcher execution.
   *
   * @param init - Denial, requirement, provider and fetcher execution identity.
   */
  constructor(init: RequireRolesFetcherRecoveryInit) {
    nextId += 1;
    this.id = `require-roles-fetcher-${nextId}`;
    this.error = init.error;
    this.requirement = init.requirement;
    this.#provider = init.provider;
    this.operation = init.operation;
    this.key = init.key;
    this.routeId = init.routeId;
    this.settled = new Promise<void>((resolve, reject) => {
      this.#resolve = resolve;
      this.#reject = reject;
    });
    const { signal } = init;
    // React Router aborts the request when the key is resubmitted, a navigation interrupts the
    // load or the router is disposed; nothing of the held execution may run afterwards.
    if (signal.aborted) {
      this.#end(() => this.#reject(signal.reason));
    } else {
      signal.addEventListener('abort', () => this.#end(() => this.#reject(signal.reason)), {
        once: true,
      });
    }
  }

  /**
   * Current progress of the hold.
   *
   * @returns The latest status; meaningful only while {@link pending}.
   */
  public get status(): RequireRolesFetcherRecoveryStatus {
    return this.#status;
  }

  /**
   * Whether the execution is still held.
   *
   * @returns False once resumed, dismissed or cancelled.
   */
  public get pending(): boolean {
    return this.#open;
  }

  /**
   * Checks access again with `refresh: true` and resumes the held execution when it is granted.
   *
   * Call it only after a user-driven access activation, for example as `RoleErrorView`'s
   * `onRetry`. Concurrent calls share one attempt, and the execution resumes at most once, so a
   * held action is never submitted twice.
   *
   * @returns The attempt outcome.
   */
  public retry(): Promise<RequireRolesFetcherRecoveryResult> {
    // A hold that ended has nothing left to resume.
    if (!this.#open) {
      return Promise.resolve('stale');
    }
    this.#attempt ??= this.#runAttempt().finally(() => {
      this.#attempt = undefined;
    });
    return this.#attempt;
  }

  /**
   * Ends the hold without resuming; the denial is thrown into the fetcher so React Router shows it
   * at the owner's error boundary. Does nothing when the hold already ended.
   */
  public dismiss(): void {
    this.#end(() => this.#reject(this.error));
  }

  /**
   * Subscribes to status and pending changes.
   *
   * @param listener - Called after every change.
   * @returns Unsubscribe function.
   */
  public subscribe(listener: () => void): () => void {
    this.#listeners.add(listener);
    return () => {
      this.#listeners.delete(listener);
    };
  }

  /**
   * Runs one fresh access check and resumes on success.
   *
   * @returns The attempt outcome.
   */
  async #runAttempt(): Promise<RequireRolesFetcherRecoveryResult> {
    this.#setStatus('checking');
    let granted: boolean;
    try {
      // `refresh` bypasses the provider cache so the activation the user just made is observed.
      granted = await this.#provider.hasAccessRole(this.requirement.roles, {
        required: this.requirement.mode === 'all',
        refresh: true,
      });
    } catch {
      // The hold may have ended while checking; a late failure must not revive its status.
      if (!this.#open) {
        return 'stale';
      }
      this.#setStatus('check-failed');
      return 'check-failed';
    }
    // The execution may have been cancelled or dismissed while checking; never resume it then.
    if (!this.#open) {
      return 'stale';
    }
    // Only a confirmed grant resumes; anything else keeps the execution held.
    if (granted !== true) {
      this.#setStatus('still-denied');
      return 'still-denied';
    }
    this.#end(() => this.#resolve());
    return 'resumed';
  }

  /**
   * Ends the hold once and notifies listeners.
   *
   * @param settle - Resolves or rejects {@link settled}.
   */
  #end(settle: () => void): void {
    // Each hold settles exactly once; later resume, dismiss or abort requests are ignored.
    if (!this.#open) {
      return;
    }
    this.#open = false;
    settle();
    this.#notify();
  }

  /**
   * Updates the status of a pending hold and notifies listeners.
   *
   * @param status - New status.
   */
  #setStatus(status: RequireRolesFetcherRecoveryStatus): void {
    this.#status = status;
    this.#notify();
  }

  /** Calls every listener. */
  #notify(): void {
    // Copy so listeners may unsubscribe while being notified.
    for (const listener of [...this.#listeners]) {
      listener();
    }
  }
}

export default RequireRolesFetcherRecovery;
